// Copies the shared core into the extension and the mobile app.
// Run after editing anything in core/:   npm run sync
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const core = (f) => join(root, 'core', f);

// Chrome extension
for (const f of ['sahayi-core.js', 'templates.js', 'openai.js']) copyFileSync(core(f), join(root, 'extension', f));

// Mobile app
mkdirSync(join(root, 'mobile', 'src', 'generated'), { recursive: true });
copyFileSync(core('openai.js'), join(root, 'mobile', 'src', 'generated', 'openai.js'));
const pageJs = readFileSync(core('templates.js'), 'utf8') + '\n;\n' + readFileSync(core('sahayi-core.js'), 'utf8');
writeFileSync(
  join(root, 'mobile', 'src', 'generated', 'coreBundle.js'),
  '// GENERATED by scripts/sync.mjs from core/. Do not edit.\nexport const CORE_JS = ' + JSON.stringify(pageJs) + ';\n'
);

console.log('✓ core synced to extension/ and mobile/src/generated/');
